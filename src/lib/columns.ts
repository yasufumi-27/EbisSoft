/** slug から記事を取得 */
export function getColumn(slug: string): Column | undefined {
  return columns.find((c) => c.slug === slug);
}

/** 更新日の新しい順（一覧・sitemap で使用） */
export const columnsByDate: Column[] = [...columns].sort((a, b) =>
  b.updated.localeCompare(a.updated),
);

/** 記事の本文から、目次に出す見出し（H2）だけを取り出す */
export function tableOfContents(column: Column): { id: string; text: string }[] {
  return column.body.filter((b): b is Extract<ColumnBlock, { type: "h2" }> => b.type === "h2");
}

/** 日付の表示用フォーマット（2026-08-03 → 2026年8月3日） */
export function formatDate(iso: string): string {
  const [y, m, d] = iso.split("-");
  return `${y}年${Number(m)}月${Number(d)}日`;
}
